"use strict";

// DEV FIXTURE providers. No network, no credentials, no cost.
//
// These exist so the whole admin workflow can be built and tested without a
// paid API key. Output is deliberately and visibly marked as a fixture so it
// can never be mistaken for real generated content, and every draft produced
// this way carries a `fixture_provider` warning.

const crypto = require("node:crypto");

function slugify(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

const fixtureTextProvider = {
  id: "fixture",
  kind: "text",
  model: "dev-fixture",
  isConfigured: () => true,

  async generateListing({ facts, adminInstruction, categories, brands, hasUserPhotos }) {
    const name = facts.name || "Unbenanntes Produkt";
    const brand = facts.brand || "";
    const matchedBrand = brands.find((b) => brand && b.name.toLowerCase() === brand.toLowerCase()) || null;
    const matchedCategory =
      categories.find((c) => facts.category && c.nameEn.toLowerCase() === facts.category.toLowerCase()) || null;

    return {
      providerId: "fixture",
      model: "dev-fixture",
      listing: {
        titleDe: `[FIXTURE] ${name}`,
        titleEn: `[FIXTURE] ${name}`,
        shortDescriptionDe: `[FIXTURE] Kurzbeschreibung für ${name}.`,
        shortDescriptionEn: `[FIXTURE] Short description for ${name}.`,
        descriptionDe: `[FIXTURE] Diese Beschreibung stammt aus dem Entwicklungs-Fixture und ist kein echter KI-Text.${
          adminInstruction ? ` Hinweis des Admins wurde übernommen: ${adminInstruction}` : ""
        }`,
        descriptionEn: `[FIXTURE] This description comes from the development fixture and is not real generated text.`,
        brandName: brand,
        model: facts.model || "",
        suggestedCategoryId: matchedCategory ? matchedCategory.id : null,
        categoryConfidence: matchedCategory ? "medium" : "low",
        suggestedBrandId: matchedBrand ? matchedBrand.id : null,
        brandConfidence: matchedBrand ? "medium" : "low",
        slug: slugify(`${brand} ${name}`) || `fixture-${crypto.randomBytes(4).toString("hex")}`,
        sku: facts.sku || "",
        tags: [],
        // Only echo specifications that genuinely came from the source.
        specifications: facts.specifications || [],
        seo: {
          metaTitle: `[FIXTURE] ${name} mieten | Leihfluss`,
          metaDescription: `[FIXTURE] ${name} bei Leihfluss mieten.`,
          metaKeywords: [],
          ogTitle: `[FIXTURE] ${name}`,
          ogDescription: `[FIXTURE] ${name} mieten.`,
        },
        imageBriefs: [
          { role: "primary", prompt: "Clean primary product shot on neutral background", requiresReference: false },
          { role: "alternate", prompt: "Alternative supported product view", requiresReference: true },
          { role: "lifestyle", prompt: "Realistic in-use context shot", requiresReference: true },
          { role: "detail", prompt: "Close detail of a visible feature", requiresReference: true },
          { role: "context", prompt: "Additional supporting context shot", requiresReference: true },
        ],
        warnings: [
          {
            code: "fixture_provider",
            field: "*",
            message:
              "Generated by the development fixture provider, not a real AI model. Review every field before publishing.",
          },
          ...(hasUserPhotos
            ? []
            : [{ code: "no_reference_photos", field: "images", message: "No admin photos supplied; visual accuracy is unverified." }]),
        ],
      },
    };
  },
};

// A 1x1 transparent PNG, tinted per-role via the label so fixtures are visibly distinct.
function fixturePng(label) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800">
  <rect width="800" height="800" fill="#e4e4e7"/>
  <rect x="40" y="40" width="720" height="720" rx="32" fill="#fff" stroke="#a1a1aa" stroke-width="6"/>
  <text x="400" y="380" text-anchor="middle" font-family="Arial" font-size="42" fill="#3f3f46">DEV FIXTURE</text>
  <text x="400" y="440" text-anchor="middle" font-family="Arial" font-size="32" fill="#71717a">${label}</text>
  <text x="400" y="510" text-anchor="middle" font-family="Arial" font-size="22" fill="#a1a1aa">not a real generated image</text>
</svg>`;
  return { base64: Buffer.from(svg).toString("base64"), mimeType: "image/svg+xml" };
}

const fixtureImageProvider = {
  id: "fixture",
  kind: "image",
  model: "dev-fixture",
  isConfigured: () => true,

  async generate({ brief }) {
    const { base64, mimeType } = fixturePng(brief?.role || "image");
    return { base64, mimeType, providerId: "fixture", model: "dev-fixture", isFixture: true };
  },
  async editFromReferences(args) {
    return fixtureImageProvider.generate(args);
  },
  async regenerateSingle(args) {
    return fixtureImageProvider.generate(args);
  },
};

module.exports = { fixtureTextProvider, fixtureImageProvider, slugify };
